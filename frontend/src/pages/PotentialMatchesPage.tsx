import { useCallback, useEffect, useState } from 'react';
import { Link } from 'react-router-dom';
import { CheckCircle2, RotateCcw, XCircle, HelpCircle } from 'lucide-react';
import { apiGet, apiPost, ApiRequestError } from '../services/api';
import type { Match, MatchDetail, Page, Review } from '../types';
import {
  Alert,
  Badge,
  Card,
  ConfirmDialog,
  DemoBadge,
  EmptyState,
  formatDate,
  formatScore,
  Modal,
  PageHeader,
  Pagination,
  TableSkeleton,
} from '../components/ui';
import { useToast } from '../hooks/useToast';

const STATUS_FILTERS = [
  { value: '', label: 'All' },
  { value: 'pending', label: 'Pending review' },
  { value: 'confirmed_for_investigation', label: 'Confirmed' },
  { value: 'rejected', label: 'Rejected' },
  { value: 'requires_manual_review', label: 'Manual review' },
];

export default function PotentialMatchesPage() {
  const { toast } = useToast();
  const [items, setItems] = useState<Match[]>([]);
  const [loading, setLoading] = useState(true);
  const [page, setPage] = useState(1);
  const [pages, setPages] = useState(1);
  const [total, setTotal] = useState(0);
  const [status, setStatus] = useState('');
  const [detail, setDetail] = useState<MatchDetail | null>(null);
  const [notes, setNotes] = useState('');
  const [confirmDecision, setConfirmDecision] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const params = new URLSearchParams({ page: String(page), page_size: '10' });
      if (status) params.set('status', status);
      const res = await apiGet<Page<Match>>(`/matches?${params}`);
      setItems(res.items);
      setPages(res.pages);
      setTotal(res.total);
    } catch (e: unknown) {
      toast('error', e instanceof Error ? e.message : 'Failed to load matches');
    } finally {
      setLoading(false);
    }
  }, [page, status, toast]);

  useEffect(() => {
    void load();
  }, [load]);

  const openDetail = async (m: Match) => {
    try {
      setDetail(await apiGet<MatchDetail>(`/matches/${m.id}`));
      setNotes('');
    } catch {
      toast('error', 'Failed to load match details');
    }
  };

  const submitReview = async (decision: string) => {
    if (!detail) return;
    setBusy(true);
    try {
      await apiPost(`/matches/${detail.id}/review`, { decision, notes });
      toast('success', 'Review recorded. Case status is never changed automatically.');
      setConfirmDecision(null);
      setDetail(null);
      void load();
    } catch (err) {
      toast('error', err instanceof ApiRequestError ? err.error.message : 'Review failed');
    } finally {
      setBusy(false);
    }
  };

  return (
    <div>
      <PageHeader
        title="Potential Matches"
        subtitle="Ranked candidate results from the face-matching engine. A similarity score is a technical measure — never an identification. Human verification and independent corroboration are mandatory."
      />

      <Alert kind="info" title="Review policy">
        Confirming a match only marks it "confirmed for further investigation". Update case status
        separately on the case page with a documented verification note.
      </Alert>

      <div className="mt-6 flex flex-wrap items-center gap-2">
        {STATUS_FILTERS.map((f) => (
          <button
            key={f.value}
            onClick={() => {
              setStatus(f.value);
              setPage(1);
            }}
            className={`rounded-full px-4 py-1.5 text-sm font-medium transition ${
              status === f.value ? 'bg-sky-600 text-white' : 'bg-navy-800 text-slate-300 hover:bg-navy-700'
            }`}
          >
            {f.label}
          </button>
        ))}
      </div>

      <div className="mt-4">
        {loading ? (
          <TableSkeleton rows={5} />
        ) : items.length === 0 ? (
          <EmptyState
            title="No potential matches"
            description="Candidates generated by photo search or video analysis will appear here for investigator review."
          />
        ) : (
          <div className="overflow-x-auto rounded-xl border border-navy-700">
            <table className="min-w-full divide-y divide-navy-700 text-sm">
              <thead className="bg-navy-900/70">
                <tr>
                  {['Candidate case', 'Source', 'Similarity*', 'Threshold', 'Model', 'Status', 'Received', ''].map((h) => (
                    <th key={h} className="px-4 py-3 text-left font-semibold text-slate-300">{h}</th>
                  ))}
                </tr>
              </thead>
              <tbody className="divide-y divide-navy-800 bg-navy-900/40">
                {items.map((m) => (
                  <tr key={m.id} className="hover:bg-navy-800/50">
                    <td className="px-4 py-3">
                      <Link to={`/cases/${m.candidate_case_id}`} className="font-mono text-sky-300 hover:underline">
                        {m.candidate_case_number}
                      </Link>
                      <div className="text-xs text-slate-400">{m.candidate_name ?? '(name unknown)'}</div>
                      {m.is_demo && <DemoBadge />}
                    </td>
                    <td className="px-4 py-3 text-slate-300">
                      {m.source_type.replace('_', ' ')}
                      {m.source_timestamp_seconds != null && (
                        <div className="text-xs text-slate-500">@ {m.source_timestamp_seconds.toFixed(2)}s</div>
                      )}
                    </td>
                    <td className="px-4 py-3 font-mono text-amber-300">{formatScore(m.similarity_score)}</td>
                    <td className="px-4 py-3 text-slate-300">{m.threshold_used}</td>
                    <td className="px-4 py-3 text-xs text-slate-400">{m.model_name}<br />{m.model_version}</td>
                    <td className="px-4 py-3"><Badge value={m.status} /></td>
                    <td className="px-4 py-3 text-xs text-slate-400">{formatDate(m.created_at)}</td>
                    <td className="px-4 py-3">
                      <button className="btn-secondary px-3 py-1.5" onClick={() => void openDetail(m)}>
                        Review
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
        {!loading && items.length > 0 && <Pagination page={page} pages={pages} total={total} onPage={setPage} />}
      </div>

      {/* Review modal */}
      <Modal open={!!detail} title="Review potential match" onClose={() => setDetail(null)} wide>
        {detail && (
          <div className="space-y-4">
            <div className="grid gap-3 text-sm sm:grid-cols-3">
              <div><p className="text-slate-400">Candidate case</p>
                <Link to={`/cases/${detail.candidate_case_id}`} className="font-mono text-sky-300 hover:underline">
                  {detail.candidate_case_number}
                </Link>
              </div>
              <div><p className="text-slate-400">Similarity score*</p><p className="font-mono text-amber-300">{formatScore(detail.similarity_score)}</p></div>
              <div><p className="text-slate-400">Threshold used</p><p>{detail.threshold_used}</p></div>
              <div><p className="text-slate-400">Model</p><p>{detail.model_name} ({detail.model_version})</p></div>
              <div><p className="text-slate-400">Processing time</p><p>{formatDate(detail.processing_timestamp)}</p></div>
              <div><p className="text-slate-400">Status</p><Badge value={detail.status} /></div>
            </div>

            <Alert kind="warning">
              * Similarity is a technical embedding-distance measure — NOT the probability that the
              images show the same person. Do not treat candidates as identifications.
            </Alert>

            {detail.reviews.length > 0 && (
              <div>
                <h3 className="mb-2 text-sm font-semibold text-slate-200">Review history</h3>
                <ul className="space-y-2">
                  {detail.reviews.map((r: Review) => (
                    <li key={r.id} className="rounded-md border border-navy-600 bg-navy-800/50 p-3 text-sm">
                      <div className="flex items-center gap-2">
                        <Badge value={r.decision} />
                        <span className="text-xs text-slate-400">{r.reviewer_name} · {formatDate(r.created_at)}</span>
                      </div>
                      {r.notes && <p className="mt-1 text-slate-300">{r.notes}</p>}
                    </li>
                  ))}
                </ul>
              </div>
            )}

            <div>
              <label className="label">Investigator notes (required to confirm)</label>
              <textarea
                className="input min-h-[90px]"
                value={notes}
                onChange={(e) => setNotes(e.target.value)}
                placeholder="Document your verification reasoning and planned corroborating steps."
              />
            </div>

            <div className="flex flex-wrap justify-end gap-2">
              <button className="btn-secondary" disabled={busy} onClick={() => setConfirmDecision('requires_manual_review')}>
                <HelpCircle className="h-4 w-4" /> Needs manual review
              </button>
              <button className="btn-danger" disabled={busy} onClick={() => setConfirmDecision('rejected')}>
                <XCircle className="h-4 w-4" /> Reject candidate
              </button>
              <button className="btn-primary" disabled={busy} onClick={() => setConfirmDecision('confirmed_for_investigation')}>
                <CheckCircle2 className="h-4 w-4" /> Confirm for investigation
              </button>
            </div>
          </div>
        )}
      </Modal>

      <ConfirmDialog
        open={!!confirmDecision}
        title="Record review decision"
        message={
          confirmDecision === 'confirmed_for_investigation'
            ? 'Confirm this candidate for further investigation? This does NOT identify anyone and does NOT change case status. Your notes will be stored in the review history.'
            : confirmDecision === 'rejected'
              ? 'Reject this candidate? The record will be retained only as long as the approved retention policy requires, in restricted audit records.'
              : 'Mark this candidate as requiring manual review?'
        }
        confirmLabel={confirmDecision === 'rejected' ? 'Reject' : 'Record decision'}
        danger={confirmDecision === 'rejected'}
        onCancel={() => setConfirmDecision(null)}
        onConfirm={() => void submitReview(confirmDecision!)}
      />
    </div>
  );
}
